const assert = require('node:assert/strict')
const { EventEmitter } = require('node:events')
const fs = require('node:fs'), path = require('node:path')
const { buildSync } = require('esbuild')
const temp = path.resolve('test-output/update-controller-test.cjs')
fs.mkdirSync('test-output', { recursive: true })
buildSync({ entryPoints: ['electron/update-controller.ts'], outfile: temp, bundle: true, platform: 'node', format: 'cjs' })
const { createUpdateController } = require(temp)
function setup(overrides = {}) {
  const updater = new EventEmitter(), events = [], locks = [], quits = []
  let checks = 0
  updater.checkForUpdates = async () => { checks++; updater.emit('update-not-available', { version: '1.0.5' }) }
  updater.quitAndInstall = (...args) => quits.push(args)
  const controller = createUpdateController({ updater, isPackaged: () => true, emit: s => events.push(s), canInstall: async () => true, confirmInstall: async () => true, lockInteraction: value => locks.push(value), ...overrides })
  return { updater, controller, events, locks, quits, checks: () => checks }
}
;(async () => {
  const normal = setup()
  assert.equal(normal.updater.autoDownload, true)
  assert.equal(normal.updater.autoInstallOnAppQuit, false)
  assert.equal(normal.updater.allowDowngrade, false)
  assert.equal(normal.updater.allowPrerelease, false)
  const a = normal.controller.check(), b = normal.controller.check()
  assert.equal(a, b); await a; assert.equal(normal.checks(), 1)
  assert.equal(normal.controller.getStatus().status, 'not-available')
  assert.equal((await normal.controller.install()).status, 'blocked')
  normal.updater.emit('update-available', { version: '1.0.6' })
  normal.updater.emit('download-progress', { percent: 51.2 })
  assert.equal(normal.controller.getStatus().percent, 51)
  normal.updater.emit('update-downloaded', { version: '1.0.6' })
  assert.equal(normal.controller.getStatus().readyToInstall, true)
  await normal.controller.check(); assert.equal(normal.checks(), 1)
  assert.equal(normal.quits.length, 0, 'Downloading must never install by itself')
  assert.equal((await normal.controller.install()).status, 'restarting')
  assert.deepEqual(normal.quits, [[false, true]])
  assert.equal((await normal.controller.install()).status, 'busy')
  normal.updater.emit('error', new Error('Install failed'))
  assert.equal(normal.locks.at(-1), false)
  const dirty = setup({ canInstall: async () => false })
  dirty.updater.emit('update-downloaded', { version: '1.0.6' })
  assert.equal((await dirty.controller.install()).status, 'blocked'); assert.equal(dirty.quits.length, 0)
  const cancelled = setup({ confirmInstall: async () => false })
  cancelled.updater.emit('update-downloaded', { version: '1.0.6' })
  assert.equal((await cancelled.controller.install()).status, 'cancelled'); assert.equal(cancelled.quits.length, 0)
  let guard = 0
  const race = setup({ canInstall: async () => ++guard === 1 })
  race.updater.emit('update-downloaded', { version: '1.0.6' })
  assert.equal((await race.controller.install()).status, 'blocked'); assert.equal(race.quits.length, 0)
  assert.deepEqual(race.locks, [true, false], 'Input locked while fresh safety check runs; unlocked on late edit')
  const unknown = setup({ canInstall: async () => { throw Error('Renderer unavailable') } })
  unknown.updater.emit('update-downloaded', { version: '1.0.6' })
  assert.equal((await unknown.controller.install()).status, 'error'); assert.equal(unknown.quits.length, 0)
  const offline = setup(); offline.updater.checkForUpdates = async () => { throw Error('Offline') }
  assert.equal((await offline.controller.check()).status, 'error')
  const stalled = setup({ checkTimeoutMs: 5 })
  stalled.updater.checkForUpdates = () => new Promise(() => {})
  assert.equal((await stalled.controller.check()).status, 'error')
  stalled.updater.checkForUpdates = async () => stalled.updater.emit('update-not-available', { version: '1.0.5' })
  assert.equal((await stalled.controller.check()).status, 'not-available', 'Timed-out checks must permit a later retry')
  const dev = setup({ isPackaged: () => false })
  assert.equal((await dev.controller.check()).status, 'dev'); assert.equal((await dev.controller.install()).status, 'dev'); assert.equal(dev.checks(), 0)
  console.log('PASS: auto-download; no install on quit; coalesced checks; cached ready state; progress; explicit install; dirty/busy/unknown guards; cancel; second guard under input lock; errors unlock; dev mode. Updater adapter is mocked.')
})().catch(error => { console.error(error); process.exitCode = 1 }).finally(() => fs.rmSync(temp, { force: true }))
