const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
const Module = require('node:module')

const source = fs.readFileSync('src/lib/lru-cache.ts', 'utf8')
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText
const testModule = new Module.Module('lru-cache-regression')
testModule._compile(compiled, 'src/lib/lru-cache.ts')
const { LRU } = testModule.exports

const disposed = []
const value = (id, bytes) => ({ id, bytes, close: () => disposed.push(id) })
const cache = new LRU(3, 10, item => item.bytes)
const a = value('a', 4), b = value('b', 4), c = value('c', 4)
cache.set('a', a); cache.set('b', b); cache.get('a'); cache.set('c', c)
assert.deepEqual(cache.keys(), ['a', 'c'])
assert.deepEqual(disposed, ['b'])
assert.equal(cache.weight, 8)

const replacement = value('a2', 3)
cache.set('a', replacement)
assert.deepEqual(disposed, ['b', 'a'])
assert.equal(cache.weight, 7)
cache.delete('c')
assert.deepEqual(disposed, ['b', 'a', 'c'])
assert.equal(cache.weight, 3)
cache.clear()
assert.deepEqual(disposed, ['b', 'a', 'c', 'a2'])
assert.equal(cache.size, 0)
assert.equal(cache.weight, 0)

const countBound = new LRU(1)
const x = value('x', 1), y = value('y', 1)
countBound.set('x', x); countBound.set('y', y)
assert.deepEqual(countBound.keys(), ['y'])
assert.deepEqual(disposed, ['b', 'a', 'c', 'a2', 'x'])
const bounded = new LRU(3, 10, item => item.bytes)
const retained=value('retained',3), oversized=value('oversized',20)
bounded.set('r',retained); bounded.set('r',retained)
assert(!disposed.includes('retained'),'reusing the same bitmap must not close it')
bounded.set('big',oversized)
assert.equal(bounded.get('r'),retained); assert.equal(bounded.weight,3)
assert(disposed.includes('oversized'),'oversized bitmap must be released without flushing other entries')
const disabled=new LRU(0); disabled.set('z',value('zero-capacity',1))
assert.equal(disabled.size,0);assert(disposed.includes('zero-capacity'))
console.log('PASS: LRU count/weight eviction, oversized exclusion, same-object replacement, zero capacity, disposal, and accounting.')
